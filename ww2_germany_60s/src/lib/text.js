/**
 * text.js — typography: typewriter date cards and word-by-word highlight subtitles.
 * Subtitles are rendered by canvas (never ffmpeg drawtext) and timed from narration_timing.json.
 */
'use strict';

const { clamp, seg, rgba, easeOutBack, easeOutCubic } = require('./easing');
const { spacedText } = require('./draw');

const SUB_Y = 1350;           // subtitle baseline center (inside safe zone)
const SUB_MAX_W = 920;
const SUB_FONT = 68;
const HIGHLIGHT = '#e8c170';

// ---- date cards -------------------------------------------------------------------------------
/**
 * Date card with typewriter reveal + blinking cursor. One key-click SFX per character is
 * generated by timeline.resolve() using the same DATE_TYPE_INTERVAL.
 */
function drawDateCard(ctx, card, time, sceneEnd, { interval, y = 420, size = 100 } = {}) {
  const t = time - card.startSec;
  if (t < -0.05) return;
  const fadeOut = 1 - seg(time, sceneEnd - 0.4, sceneEnd - 0.12);
  if (fadeOut <= 0) return;
  const chars = [...card.text];
  const shown = clamp(Math.floor(t / interval) + 1, 0, chars.length);
  const typed = chars.slice(0, shown).join('');
  const done = shown >= chars.length;

  ctx.save();
  ctx.globalAlpha = fadeOut;
  // feathered dark band behind the card
  const bandA = easeOutCubic(seg(t, 0, 0.25)) * 0.62;
  const g = ctx.createLinearGradient(0, y - 120, 0, y + 120);
  g.addColorStop(0, 'rgba(8,8,8,0)');
  g.addColorStop(0.3, `rgba(8,8,8,${bandA})`);
  g.addColorStop(0.7, `rgba(8,8,8,${bandA})`);
  g.addColorStop(1, 'rgba(8,8,8,0)');
  ctx.fillStyle = g;
  ctx.fillRect(0, y - 120, 1080, 240);

  ctx.font = `700 ${size}px Oswald`;
  ctx.textBaseline = 'middle';
  const spacing = 6;
  // measure the full string so letters don't shift while typing
  const full = [...card.text].reduce((s, c) => s + ctx.measureText(c).width, 0) + spacing * (chars.length - 1);
  let x = 540 - full / 2;
  chars.forEach((c, i) => {
    const w = ctx.measureText(c).width;
    if (i < shown) {
      const age = t - i * interval;
      const a = clamp(age / 0.04);
      ctx.fillStyle = `rgba(0,0,0,${0.7 * a})`;
      ctx.fillText(c, x + 3, y + 4);
      ctx.fillStyle = rgba('#e9e3d4', a);
      ctx.fillText(c, x, y + (1 - a) * -6);
    }
    x += w + spacing;
  });
  // cursor
  if (!done || Math.floor(t * 2.6) % 2 === 0) {
    const cx = 540 - full / 2 + chars.slice(0, shown).reduce((s, c) => s + ctx.measureText(c).width + spacing, 0) + 2;
    ctx.fillStyle = rgba(HIGHLIGHT, done ? 0.75 : 1);
    ctx.fillRect(cx, y - size * 0.38, 7, size * 0.76);
  }
  // rules above/below grow out from center once typed
  const r = easeOutCubic(seg(t, chars.length * interval, chars.length * interval + 0.45));
  if (r > 0) {
    ctx.fillStyle = rgba('#d8d2c4', 0.55);
    const hw = (full / 2 + 30) * r;
    ctx.fillRect(540 - hw, y - size * 0.72, hw * 2, 2);
    ctx.fillRect(540 - hw, y + size * 0.68, hw * 2, 2);
  }
  ctx.restore();
  return typed;
}

// ---- subtitles --------------------------------------------------------------------------------
/** Split narration words into 2–4 word chunks, breaking after punctuation. */
function chunkWords(words) {
  const chunks = [];
  let cur = [];
  const endsSentence = (w) => /[.!?]$/.test(w.text);
  words.forEach((w, i) => {
    cur.push(w);
    const comma = /[,;:]$/.test(w.text);
    const next = words[i + 1];
    // break: sentence end always; comma once we have 2+; at 4 words; avoid leaving 1 word before a sentence end
    const tailOfSentence = next && endsSentence(next) && cur.length === 3;
    if (endsSentence(w) || (comma && cur.length >= 2) || cur.length === 4 || tailOfSentence) { chunks.push(cur); cur = []; }
  });
  if (cur.length) chunks.push(cur);
  // never leave a 1-word chunk: merge it into a neighbour, never across a sentence end
  for (let i = 0; i < chunks.length; i++) {
    if (chunks[i].length !== 1 || chunks.length === 1) continue;
    const w = chunks[i][0];
    const prev = chunks[i - 1], next = chunks[i + 1];
    const canPrev = prev && prev.length < 4 && !endsSentence(prev[prev.length - 1]);
    const canNext = next && next.length < 4 && !endsSentence(w);
    if (canPrev && (endsSentence(w) || !canNext)) { prev.push(w); chunks.splice(i, 1); i--; }
    else if (canNext) { chunks[i + 1] = [w, ...next]; chunks.splice(i, 1); i--; }
    else if (prev && prev.length >= 3 && !endsSentence(prev[prev.length - 1])) chunks[i] = [prev.pop(), w]; // borrow a word
  }
  return chunks;
}

/** All subtitle chunks for the timeline with absolute display windows. */
function buildSubtitles(tl) {
  const out = [];
  for (const sc of tl.scenes) {
    const chunks = chunkWords(sc.narration.words);
    chunks.forEach((c, i) => {
      const start = Math.max(sc.startSec + 0.05, c[0].start - 0.06);
      const next = chunks[i + 1];
      const end = next ? next[0].start - 0.06 : Math.min(sc.endSec - 0.1, c[c.length - 1].end + 0.25);
      out.push({ scene: sc.id, start, end, words: c });
    });
  }
  return out;
}

function drawSubtitles(ctx, subs, time, alpha = 1) {
  const sub = subs.find((s) => time >= s.start && time < s.end);
  if (!sub || alpha <= 0) return;
  const words = sub.words.map((w) => w.text.toUpperCase());
  let size = SUB_FONT;
  ctx.save();
  const measure = () => {
    ctx.font = `700 ${size}px Oswald`;
    const space = ctx.measureText(' ').width * 1.15;
    const ws = words.map((w) => ctx.measureText(w).width);
    return { ws, space, total: ws.reduce((a, b) => a + b, 0) + space * (ws.length - 1) };
  };
  let m = measure();
  while (m.total > SUB_MAX_W && size > 44) { size -= 2; m = measure(); }
  // pop-in
  const age = time - sub.start;
  const sc = 0.9 + 0.1 * easeOutBack(clamp(age / 0.16));
  ctx.globalAlpha = alpha * clamp(age / 0.08) * clamp((sub.end - time) / 0.06);
  ctx.translate(540, SUB_Y);
  ctx.scale(sc, sc);
  ctx.textBaseline = 'middle';
  ctx.lineJoin = 'round';
  ctx.miterLimit = 2;
  let x = -m.total / 2;
  sub.words.forEach((w, i) => {
    const nextStart = i + 1 < sub.words.length ? sub.words[i + 1].start : sub.end;
    const active = time >= w.start - 0.03 && time < nextStart;
    ctx.strokeStyle = '#000';
    ctx.lineWidth = 8; // 4 px visible outside the glyph
    ctx.strokeText(words[i], x, 0);
    ctx.fillStyle = active ? HIGHLIGHT : (time >= w.start ? '#ffffff' : 'rgba(255,255,255,0.92)');
    ctx.fillText(words[i], x, 0);
    x += m.ws[i] + m.space;
  });
  ctx.restore();
}

/** SRT export (clean, chunked the same way as the burn-in). */
function toSrt(subs) {
  const ts = (s) => {
    const ms = Math.round(s * 1000);
    const h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, sec = Math.floor(ms / 1000) % 60, r = ms % 1000;
    return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')},${String(r).padStart(3, '0')}`;
  };
  return subs.map((s, i) => `${i + 1}\n${ts(s.start)} --> ${ts(s.end)}\n${s.words.map((w) => w.text).join(' ')}\n`).join('\n');
}

/** Centered multi-line text block helper (used by the hook and ending). */
function wrapLines(ctx, text, maxW) {
  const words = text.split(' ');
  const lines = [];
  let cur = '';
  for (const w of words) {
    const t = cur ? cur + ' ' + w : w;
    if (ctx.measureText(t).width > maxW && cur) { lines.push(cur); cur = w; } else cur = t;
  }
  if (cur) lines.push(cur);
  return lines;
}

module.exports = { drawDateCard, buildSubtitles, drawSubtitles, toSrt, chunkWords, wrapLines, spacedText, SUB_Y, HIGHLIGHT };
